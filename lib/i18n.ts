export const isLang = (v: unknown): v is Lang => v === 'en' || v === 'ne' || v === 'ja';

/**
 * Language detection by script. Devanagari means Nepali (Hindi shares the script, and is treated as Nepali too), and
 * kana or kanji means Japanese. Latin text returns null on purpose: English is also what people type when their UI is
 * in Nepali or Japanese, so it never forces a switch back.
 */
export function detectLang(text: string): Lang | null {
  const letters = text.replace(/[\s\d\p{P}\p{S}]/gu, '');
  if (letters.length < 2) return null;
  const count = (re: RegExp) => (letters.match(re) ?? []).length;
  const devanagari = count(/[ऀ-ॿ]/g);
  const japanese = count(/[぀-ヿ一-鿿ｦ-ﾟ]/g);
  if (devanagari / letters.length >= 0.4) return 'ne';
  if (japanese / letters.length >= 0.4) return 'ja';
  return null;
}

